export type TKey = keyof (typeof DICT)['pt']

interface I18nStore {
  lang: Lang
  setLang: (l: Lang) => void
  toggle: () => void
}

const LANGUAGE_STORAGE_KEY = 'iara.language'

function initialLanguage(): Lang {
  try {
    const saved = window.localStorage.getItem(LANGUAGE_STORAGE_KEY)
    if (saved === 'pt' || saved === 'en') return saved
  } catch {}

  if (typeof navigator !== 'undefined') {
    for (const locale of [...(navigator.languages ?? []), navigator.language]) {
      const lang = locale?.toLowerCase().split('-')[0]
      if (lang === 'pt' || lang === 'en') return lang
    }
  }
  return 'en'
}

export const useI18n = create<I18nStore>((set, get) => ({
  lang: initialLanguage(),
  setLang: (lang) => {
    try {
      window.localStorage.setItem(LANGUAGE_STORAGE_KEY, lang)
    } catch {}
    set({ lang })
  },
  toggle: () => get().setLang(get().lang === 'pt' ? 'en' : 'pt'),
}))

export function useT(): (k: TKey, vars?: Record<string, string>) => string {
  const lang = useI18n((s) => s.lang)
  return (k, vars) => {
    const raw = DICT[lang][k] ?? k
    if (!vars) return raw
    return Object.entries(vars).reduce(
      (acc, [name, val]) => acc.replace(`{${name}}`, val),
      raw
    )
  }
}
